"""ANSI colour tokens shared by the CLI and training output."""


class Colours:
    """Design System ANSI Colour Tokens for console formatting."""

    RESET = "\033[0m"
    NAVY = "\033[34m"
    ROYAL_BLUE = "\033[94m"
    CYAN = "\033[36m"
    BRIGHT_CYAN = "\033[96m"
    BOLD_CYAN = "\033[1;36m"
